import assert from "node:assert/strict";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import prettier from "prettier";

import type { RollupDefinition } from "../src/types";

const HEADER = "// Generated by pnpm rollups:sync. Do not edit.\n";

export function validateDefinitions(
  definitions: (RollupDefinition & { id: string })[]
) {
  const ids = new Set<string>();
  const posters = new Map<string, string>();
  for (const definition of definitions) {
    const { id, name, color, icon, blobPosters, iconClassname } = definition;
    assert(
      typeof id === "string" && /^[a-z][a-z0-9]*$/.test(id),
      `Invalid rollup ID: ${id}`
    );
    assert(!ids.has(id), `Duplicate rollup ID: ${id}`);
    ids.add(id);
    assert(typeof name === "string" && name.trim(), `${id}: name is required`);
    assert(
      color &&
        /^#[\da-f]{6}$/i.test(color.light) &&
        /^#[\da-f]{6}$/i.test(color.dark),
      `${id}: invalid theme colors`
    );
    assert(
      typeof icon === "string" && /^icon\.(svg|png|jpg|jpeg)$/.test(icon),
      `${id}: invalid icon filename`
    );
    assert(
      iconClassname === undefined || typeof iconClassname === "string",
      `${id}: invalid icon classes`
    );
    assert(
      blobPosters &&
        typeof blobPosters === "object" &&
        !Array.isArray(blobPosters),
      `${id}: blobPosters is required`
    );
    for (const [chainId, addresses] of Object.entries(blobPosters)) {
      assert(
        /^[1-9]\d*$/.test(chainId) && Number.isSafeInteger(Number(chainId)),
        `${id}: invalid chain ID ${chainId}`
      );
      assert(
        Array.isArray(addresses) && addresses.length,
        `${id}: empty poster list for ${chainId}`
      );
      for (const address of addresses) {
        assert(
          typeof address === "string" && /^0x[\da-f]{40}$/i.test(address),
          `${id}: invalid poster address ${address}`
        );
        const key = `${chainId}:${address.toLowerCase()}`;
        assert(
          !posters.has(key),
          `${id}: duplicate poster ${address} on chain ${chainId} (already assigned to ${posters.get(
            key
          )})`
        );
        posters.set(key, id);
      }
    }
  }
}

export function updatePrismaEnum(schema: string, ids: string[]) {
  const current = schema.match(/enum Rollup \{[\s\S]*?\n\}/);
  assert(current, "Prisma Rollup enum was not found");
  const previous = [...current[0].matchAll(/^\s+(\w+)\s+@map\("([^"]+)"\)/gm)];
  for (const [, key, id] of previous) {
    assert(
      id && ids.includes(id) && key === id.toUpperCase(),
      `Cannot remove or rename stored rollup ID: ${id}`
    );
  }
  // Preserve the current order to avoid changes to existing enum values.
  const orderedIds = [
    ...previous.map((match) => match[2]!),
    ...ids.filter((id) => !previous.some((match) => match[2] === id)),
  ];
  const width = Math.max(...orderedIds.map((id) => id.length));
  const replacement = `enum Rollup {\n${orderedIds
    .map((id) => `  ${id.toUpperCase().padEnd(width)} @map("${id}")`)
    .join("\n")}\n\n  @@map("rollup")\n}`;
  return schema.replace(current[0], replacement);
}

export async function syncRollups(root: string, check = false) {
  const packageDir = path.join(root, "packages/rollups");
  const sourceDir = path.join(packageDir, "src");
  const rollupsDir = path.join(sourceDir, "rollups");
  const entries = (await readdir(rollupsDir, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  assert(entries.length, "No rollup definitions found");
  const definitions: (RollupDefinition & { id: string })[] = [];
  for (const id of entries) {
    const module = await import(
      pathToFileURL(path.join(rollupsDir, id, "definition.ts")).href
    );
    const definition = module.default as RollupDefinition;
    assert(
      definition &&
        typeof definition === "object" &&
        !Array.isArray(definition),
      `${id}: definition must be an object`
    );
    assert(
      !Object.hasOwn(definition, "id"),
      `${id}: remove the id field; the folder name supplies the ID`
    );
    definitions.push({ ...definition, id });
  }
  validateDefinitions(definitions);
  for (const definition of definitions) {
    await readFile(path.join(rollupsDir, definition.id, definition.icon));
  }
  const options = await prettier.resolveConfig(
    path.join(root, ".prettierrc.json")
  );
  const format = (text: string) =>
    prettier.format(text, { ...options, parser: "typescript" });
  const registry =
    HEADER +
    definitions
      .map(
        ({ id }) => `import rollup_${id} from "../rollups/${id}/definition";`
      )
      .join("\n") +
    `\n\nexport const ROLLUP_DEFINITIONS = {\n${entries
      .map((id) => `${id}: { ...rollup_${id}, id: "${id}" as const }`)
      .join(",\n")}\n};\n`;
  const icons =
    HEADER +
    '// Load asset types only for the icon export.\n// eslint-disable-next-line @typescript-eslint/triple-slash-reference\n/// <reference path="../assets.d.ts" />\n' +
    definitions
      .map(
        ({ id, icon }) => `import icon_${id} from "../rollups/${id}/${icon}";`
      )
      .join("\n") +
    `\n\nexport const rollupIcons = {\n${definitions
      .map(
        ({ id, icon }) =>
          `${id}: icon_${id}${icon.endsWith(".svg") ? "" : ".src"}`
      )
      .join(",\n")}\n};\n`;
  const schemaPath = path.join(root, "packages/db/prisma/schema/enums.prisma");
  const schema = await readFile(schemaPath, "utf8");
  const updatedSchema = updatePrismaEnum(schema, entries);
  const outputs = new Map([
    [path.join(sourceDir, "generated/registry.ts"), format(registry)],
    [path.join(sourceDir, "generated/icons.ts"), format(icons)],
    [schemaPath, updatedSchema],
  ]);
  const changed: string[] = [];
  for (const [file, contents] of outputs) {
    const previous = await readFile(file, "utf8").catch(
      (error: NodeJS.ErrnoException) => {
        if (error.code === "ENOENT") return undefined;
        throw error;
      }
    );
    if (previous === contents) continue;
    changed.push(path.relative(root, file));
    if (!check) {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, contents);
    }
  }
  if (check && changed.length)
    throw new Error(`Run pnpm rollups:sync to update:\n${changed.join("\n")}`);
  return { changed, migrationRequired: schema !== updatedSchema };
}
